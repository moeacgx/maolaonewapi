package model

import (
	"github.com/QuantumNous/new-api/common"

	"gorm.io/gorm"
	"gorm.io/gorm/clause"
)

// lockForUpdate emits SELECT ... FOR UPDATE for transactional reads.
// GORM v2 ignores the old Set("gorm:query_option", "FOR UPDATE") form.
func lockForUpdate(tx *gorm.DB) *gorm.DB {
	if common.UsingSQLite {
		return tx
	}
	return tx.Clauses(clause.Locking{Strength: "UPDATE"})
}
